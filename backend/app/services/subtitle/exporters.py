"""Subtitle exporters: SRT, VTT, TXT, JSON, ASS (section 12).

- Timestamps are converted to strings only here, never before.
- SRT uses CRLF line endings and UTF-8 (optionally with BOM) for Windows
  compatibility; VTT/TXT/JSON use LF; ASS uses CRLF.
- Numbering is always re-sequenced so exported files are valid even if the
  editor leaves gaps.
"""

from __future__ import annotations

import json
import logging
import re
from abc import ABC, abstractmethod
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from app.core.errors import ExportError
from app.services.subtitle.models import Subtitle

logger = logging.getLogger(__name__)


def format_timestamp_srt(ms: int) -> str:
    """Format milliseconds as an SRT timestamp: HH:MM:SS,mmm."""
    if ms < 0:
        ms = 0
    hours = ms // 3_600_000
    minutes = (ms % 3_600_000) // 60_000
    seconds = (ms % 60_000) // 1000
    milliseconds = ms % 1000
    return f"{hours:02}:{minutes:02}:{seconds:02},{milliseconds:03}"


def format_timestamp_vtt(ms: int) -> str:
    """Format milliseconds as a WebVTT timestamp: HH:MM:SS.mmm."""
    return format_timestamp_srt(ms).replace(",", ".")


def format_timestamp_ass(ms: int) -> str:
    """Format milliseconds as an ASS timestamp: H:MM:SS.cc (single-digit
    hour, centiseconds - the ASS resolution)."""
    if ms < 0:
        ms = 0
    hours = ms // 3_600_000
    minutes = (ms % 3_600_000) // 60_000
    seconds = (ms % 60_000) // 1000
    centiseconds = (ms % 1000) // 10
    return f"{hours}:{minutes:02}:{seconds:02}.{centiseconds:02}"


_HEX_COLOR = re.compile(r"^#?([0-9a-fA-F]{6})$")


def rgb_to_ass_color(value: str) -> str:
    """Convert ``#RRGGBB`` (or ``RRGGBB``) to an ASS ``&HAABBGGRR`` colour -
    opaque alpha, BGR byte order (ASS colours are not RGB)."""
    match = _HEX_COLOR.match(value.strip())
    if match is None:
        raise ExportError(f"Invalid colour '{value}'. Use RRGGBB hex, e.g. FFFFFF.")
    rgb = match.group(1)
    return f"&H00{rgb[4:6]}{rgb[2:4]}{rgb[0:2]}".upper()


def sanitize_ass_value(value: str) -> str:
    """Strip characters that would break the comma-separated Style line."""
    return re.sub(r"[,{}\r\n]", "", value).strip()


@dataclass(frozen=True)
class ASSStyle:
    """A single ``[V4+ Styles]`` Default style (the subset we expose)."""

    font_name: str = "Arial"
    font_size: float = 48.0
    #: ASS &HAABBGGRR colours (build via :func:`rgb_to_ass_color`)
    primary_color: str = "&H00FFFFFF"
    outline_color: str = "&H00000000"
    back_color: str = "&H80000000"
    bold: bool = False
    italic: bool = False
    outline: float = 2.0
    shadow: float = 0.0
    #: numpad alignment: 1..3 bottom, 4..6 middle, 7..9 top (2 = bottom-center)
    alignment: int = 2
    margin_l: int = 10
    margin_r: int = 10
    margin_v: int = 40
    play_res_x: int = 1920
    play_res_y: int = 1080

    def to_style_line(self) -> str:
        bold = "-1" if self.bold else "0"
        italic = "-1" if self.italic else "0"
        font = sanitize_ass_value(self.font_name) or "Arial"
        return (
            f"Style: Default,{font},{self.font_size:g},"
            f"{self.primary_color},&H000000FF,{self.outline_color},{self.back_color},"
            f"{bold},{italic},0,0,100,100,0,0,1,"
            f"{self.outline:g},{self.shadow:g},{self.alignment},"
            f"{self.margin_l},{self.margin_r},{self.margin_v},1"
        )

    def to_header(self) -> str:
        return (
            "[Script Info]\r\n"
            "; Generated by VideoToSRT\r\n"
            "ScriptType: v4.00+\r\n"
            f"PlayResX: {self.play_res_x}\r\n"
            f"PlayResY: {self.play_res_y}\r\n"
            "WrapStyle: 0\r\n"
            "ScaledBorderAndShadow: yes\r\n"
            "\r\n"
            "[V4+ Styles]\r\n"
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
            "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
            "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
            "Alignment, MarginL, MarginR, MarginV, Encoding\r\n"
            f"{self.to_style_line()}\r\n"
            "\r\n"
            "[Events]\r\n"
            "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, "
            "Effect, Text\r\n"
        )


class SubtitleExporter(ABC):
    """Base class for subtitle exporters."""

    format_name: str = "txt"
    extension: str = "txt"
    line_ending: str = "\n"

    @abstractmethod
    def render(self, subtitles: Sequence[Subtitle]) -> str:
        """Render the full subtitle document as a string."""

    def export(
        self, subtitles: Sequence[Subtitle], path: Path | str, utf8_bom: bool = False
    ) -> Path:
        path = Path(path)
        content = self.render(subtitles)
        encoding = "utf-8-sig" if utf8_bom else "utf-8"
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding=encoding, newline="") as handle:
                handle.write(content)
        except OSError as exc:
            raise ExportError(f"Could not write export file: {exc}") from exc
        logger.info("Exported %d subtitles to %s (%s).", len(subtitles), path, self.format_name)
        return path


class SRTExporter(SubtitleExporter):
    format_name = "srt"
    extension = "srt"
    line_ending = "\r\n"

    def __init__(self, prefix_speakers: bool = False) -> None:
        self.prefix_speakers = prefix_speakers

    def render(self, subtitles: Sequence[Subtitle]) -> str:
        blocks: list[str] = []
        for number, sub in enumerate(subtitles, start=1):
            start = format_timestamp_srt(sub.start_ms)
            end = format_timestamp_srt(sub.end_ms)
            text = sub.text.strip().replace("\r\n", "\n").replace("\n", "\r\n")
            if not text.replace("\r\n", "").strip():
                continue  # empty entries would produce invalid blocks
            if self.prefix_speakers and sub.speaker:
                text = f"[{sub.speaker}] {text}"
            blocks.append(f"{number}\r\n{start} --> {end}\r\n{text}\r\n")
        return "\r\n".join(blocks)  # blank line between entries


class VTTExporter(SubtitleExporter):
    format_name = "vtt"
    extension = "vtt"

    def __init__(self, prefix_speakers: bool = False) -> None:
        self.prefix_speakers = prefix_speakers

    def render(self, subtitles: Sequence[Subtitle]) -> str:
        lines: list[str] = ["WEBVTT", ""]
        for sub in subtitles:
            text = sub.text.strip()
            if not text:
                continue
            if self.prefix_speakers and sub.speaker:
                text = f"[{sub.speaker}] {text}"
            lines.append(f"{format_timestamp_vtt(sub.start_ms)} --> {format_timestamp_vtt(sub.end_ms)}")
            lines.append(text)
            lines.append("")
        return "\n".join(lines)


class TXTExporter(SubtitleExporter):
    format_name = "txt"
    extension = "txt"

    def __init__(self, prefix_speakers: bool = False) -> None:
        self.prefix_speakers = prefix_speakers

    def render(self, subtitles: Sequence[Subtitle]) -> str:
        paragraphs: list[str] = []
        for sub in subtitles:
            text = sub.text.replace("\n", " ").strip()
            if not text:
                continue
            if self.prefix_speakers and sub.speaker:
                text = f"[{sub.speaker}] {text}"
            paragraphs.append(text)
        return "\n".join(paragraphs) + "\n"


class JSONExporter(SubtitleExporter):
    format_name = "json"
    extension = "json"

    def render(self, subtitles: Sequence[Subtitle]) -> str:
        payload = {"subtitles": [sub.to_dict() for sub in subtitles]}
        return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


class ASSExporter(SubtitleExporter):
    """Advanced SubStation Alpha (ASS/SSA v4+) with one styled track.

    ASS carries its own styling (font, colours, outline, position) in the
    header, which is also how the styled burn-in path renders. Braces in
    cue text are neutralised so user text can never inject override tags.
    """

    format_name = "ass"
    extension = "ass"
    line_ending = "\r\n"

    def __init__(self, style: ASSStyle | None = None) -> None:
        self.style = style or ASSStyle()

    def render(self, subtitles: Sequence[Subtitle]) -> str:
        lines = [self.style.to_header()]
        for sub in subtitles:
            text = escape_ass_text(sub.text)
            if not text:
                continue  # empty cues would render as blank Dialogue rows
            lines.append(
                f"Dialogue: 0,{format_timestamp_ass(sub.start_ms)},"
                f"{format_timestamp_ass(sub.end_ms)},Default,,0,0,0,,{text}\r\n"
            )
        return "".join(lines)


def escape_ass_text(text: str) -> str:
    """Make cue text safe for the comma-separated Dialogue line: strip
    braces (override-tag injection) and map newlines to ASS hard breaks."""
    cleaned = text.replace("\r\n", "\n").replace("{", "(").replace("}", ")")
    return "\n".join(part.strip() for part in cleaned.split("\n") if part.strip()).replace(
        "\n", r"\N"
    )


_EXPORTERS: dict[str, type[SubtitleExporter]] = {
    "srt": SRTExporter,
    "vtt": VTTExporter,
    "txt": TXTExporter,
    "json": JSONExporter,
    "ass": ASSExporter,
}


def supported_formats() -> list[str]:
    return sorted(_EXPORTERS)


def get_exporter(fmt: str) -> SubtitleExporter:
    key = fmt.lower().strip(".")
    if key not in _EXPORTERS:
        raise ExportError(
            f"Unsupported export format '{fmt}'. Supported: {', '.join(supported_formats())}"
        )
    return _EXPORTERS[key]()


def export_subtitles(
    subtitles: Sequence[Subtitle],
    path: Path | str,
    fmt: str,
    utf8_bom: bool = False,
    style: ASSStyle | None = None,
    prefix_speakers: bool = False,
) -> Path:
    """Write subtitles to ``path`` in the requested format.

    ``style`` only applies to the ASS format (styled export / burn-in);
    ``prefix_speakers`` prepends ``[Speaker]`` to labelled cues in the
    plain-text formats (srt/vtt/txt).
    """
    key = fmt.lower().strip(".")
    exporter: SubtitleExporter
    if key == "ass":
        exporter = ASSExporter(style)
    elif prefix_speakers and key in ("srt", "vtt", "txt"):
        exporter = _EXPORTERS[key](prefix_speakers=True)  # type: ignore[call-arg]
    else:
        exporter = get_exporter(fmt)
    return exporter.export(subtitles, path, utf8_bom=utf8_bom)
